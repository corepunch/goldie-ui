//  test_db_dialog_standalone.c
// Headless test of database-driven dialog infrastructure (Phase 2).
// Exercises the DDX/database plumbing without opening a real modal UI.

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "ui.h"
#include "test_framework.h"
#include "test_env.h"

// Minimal test schema matching socialfeed authors table
typedef struct {
    int id;
    char name[64];
    char avatar[256];
} test_author_t;

// Minimal generated-style table id for testing
enum { ID_DB_AUTHORS = 0 };

enum {
    ID_TEST_AUTHORS_ID = 1,
    ID_TEST_AUTHORS_NAME = 2,
    ID_TEST_AUTHORS_AVATAR = 3,
};

// Field metadata (would be generated by orionc)
static const db_field_meta_t test_author_fields[] = {
    { ID_TEST_AUTHORS_ID, "id", DB_TYPE_INT, offsetof(test_author_t, id), 0 },
    { ID_TEST_AUTHORS_NAME, "name", DB_TYPE_STRING, offsetof(test_author_t, name), 64 },
    { ID_TEST_AUTHORS_AVATAR, "avatar", DB_TYPE_STRING, offsetof(test_author_t, avatar), 256 },
};

// Minimal in-memory database for testing
typedef struct {
    test_author_t authors[10];
    int author_count;
} test_db_context_t;

// Minimal database proc for testing
static lresult_t test_db_proc(database_t *db, uint32_t msg,
                               uint32_t wparam, void *lparam) {
    test_db_context_t *ctx = (test_db_context_t *)db->userdata;
    
    switch (msg) {
        case dbCreate:
            ctx = calloc(1, sizeof(test_db_context_t));
            db->userdata = ctx;
            // Add one test author
            ctx->authors[0] = (test_author_t){ .id = 1, .name = "Alice", .avatar = "alice.png" };
            ctx->author_count = 1;
            printf("[test_db] Created database with 1 author\n");
            return 1;
            
        case dbDestroy:
            free(ctx);
            return 1;
            
        case dbFind: {
            int table_id = LOWORD(wparam);
            int author_id = (int)(intptr_t)lparam;
            if (table_id == ID_DB_AUTHORS && author_id > 0 && author_id <= ctx->author_count) {
                printf("[test_db] Found author ID %d: %s\n", author_id, ctx->authors[author_id - 1].name);
                return (lresult_t)&ctx->authors[author_id - 1];
            }
            return 0;
        }
            
        case dbInsert: {
            int table_id = wparam;
            if (table_id == ID_DB_AUTHORS && ctx->author_count < 10) {
                test_author_t *new_author = (test_author_t *)lparam;
                new_author->id = ctx->author_count + 1;
                ctx->authors[ctx->author_count] = *new_author;
                ctx->author_count++;
                printf("[test_db] Inserted author ID %d: %s\n",
                       new_author->id, new_author->name);
                return (lresult_t)&ctx->authors[ctx->author_count - 1];
            }
            return 0;
        }
            
        case dbUpdate: {
            int table_id = LOWORD(wparam);
            int author_id = HIWORD(wparam);
            if (table_id == ID_DB_AUTHORS && author_id > 0 && author_id <= ctx->author_count) {
                test_author_t *updated = (test_author_t *)lparam;
                ctx->authors[author_id - 1] = *updated;
                printf("[test_db] Updated author ID %d: %s\n", author_id, updated->name);
                return 1;
            }
            return 0;
        }
            
        default:
            return 0;
    }
}

