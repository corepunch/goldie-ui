static const form_def_t author_form = {
    .name = "Edit Author",
    .width = 300,
    .height = 150,
    .flags = WINDOW_AUTO_LAYOUT,
    .children = author_form_children,
    .child_count = 1,
    .bindings = author_bindings,
    .binding_count = 2,
    .ok_id = 100,
    .cancel_id = 101,
    .db_name = "db",
    .db_table = "authors",
    .db_table_id = ID_DB_AUTHORS,
    .db_fields = (const void *)test_author_fields,
    .db_field_count = 3,
};

static lresult_t nop_proc(window_t *win, uint32_t msg, uint32_t wparam, void *lparam) {
    (void)win;
    (void)msg;
    (void)wparam;
    (void)lparam;
    return false;
}

static database_t *create_test_database(void) {
    database_t *db = calloc(1, sizeof(database_t));
    if (!db)
        return NULL;
    db->name = "db";
    db->proc = test_db_proc;
    if (!send_db_message(db, dbCreate, 0, NULL)) {
        free(db);
        return NULL;
    }
    if (!register_database("db", db)) {
        send_db_message(db, dbDestroy, 0, NULL);
        free(db);
        return NULL;
    }
    ui_set_database(db);
    return db;
}

static void destroy_test_database(database_t *db) {
    if (!db)
        return;
    send_db_message(db, dbDestroy, 0, NULL);
    free(db);
    ui_set_database(NULL);
}

void test_db_dialog_metadata_is_self_contained(void) {
    TEST("database dialog form: generated metadata is self-contained");

    ASSERT_STR_EQUAL(author_form.db_name, "db");
    ASSERT_STR_EQUAL(author_form.db_table, "authors");
    ASSERT_EQUAL((int)author_form.db_table_id, ID_DB_AUTHORS);
    ASSERT_NOT_NULL((void *)author_form.db_fields);
    ASSERT_EQUAL(author_form.db_field_count, 3);
    ASSERT_NOT_NULL((void *)author_form.bindings);
    ASSERT_EQUAL(author_form.binding_count, 2);

    PASS();
}

void test_db_dialog_update_existing_record_headless(void) {
    TEST("database dialog plumbing: fetch, DDX pull, update existing record");

    test_env_init();
    database_t *db = create_test_database();
    ASSERT_NOT_NULL(db);

    lresult_t found = send_db_message(db, dbFind,
                                      MAKEDWORD(author_form.db_table_id, 0),
                                      (void *)(intptr_t)1);
    ASSERT_NOT_NULL((void *)found);

    test_author_t record = {0};
    memcpy(&record, (void *)found, sizeof(record));

    window_t *dlg = create_window_from_form(&author_form, 0, 0, NULL,
                                            nop_proc, 0, NULL);
    ASSERT_NOT_NULL(dlg);
    dialog_push(dlg, &record, author_form.bindings, author_form.binding_count);

    window_t *name = get_window_item(dlg, 1);
    ASSERT_NOT_NULL(name);
    send_message(name, edSetText, 0, "Alicia");

    dialog_pull(dlg, &record, author_form.bindings, author_form.binding_count);
    ASSERT_STR_EQUAL(record.name, "Alicia");
    ASSERT_TRUE(send_db_message(db, dbUpdate,
                                MAKEDWORD(author_form.db_table_id, 1),
                                &record));

    test_db_context_t *ctx = (test_db_context_t *)db->userdata;
    ASSERT_STR_EQUAL(ctx->authors[0].name, "Alicia");

    destroy_window(dlg);
    destroy_test_database(db);
    test_env_shutdown();
    PASS();
}

void test_db_dialog_insert_new_record_headless(void) {
    TEST("database dialog plumbing: DDX pull and insert new record");

    test_env_init();
    database_t *db = create_test_database();
    ASSERT_NOT_NULL(db);

    test_author_t record = {0};
    window_t *dlg = create_window_from_form(&author_form, 0, 0, NULL,
                                            nop_proc, 0, NULL);
    ASSERT_NOT_NULL(dlg);

    window_t *name = get_window_item(dlg, 1);
    window_t *avatar = get_window_item(dlg, 2);
    ASSERT_NOT_NULL(name);
    ASSERT_NOT_NULL(avatar);
    send_message(name, edSetText, 0, "Bob");
    send_message(avatar, edSetText, 0, "bob.png");

    dialog_pull(dlg, &record, author_form.bindings, author_form.binding_count);
    test_author_t *inserted = (test_author_t *)send_db_message(db, dbInsert,
                                                               author_form.db_table_id,
                                                               &record);
    ASSERT_NOT_NULL(inserted);
    ASSERT_EQUAL(inserted->id, 2);
    ASSERT_STR_EQUAL(inserted->name, "Bob");
    ASSERT_STR_EQUAL(inserted->avatar, "bob.png");

    test_db_context_t *ctx = (test_db_context_t *)db->userdata;
    ASSERT_EQUAL(ctx->author_count, 2);

    destroy_window(dlg);
    destroy_test_database(db);
    test_env_shutdown();
    PASS();
}

int main(int argc, char **argv) {
    (void)argc; (void)argv;

    TEST_START("Database Dialog Infrastructure");
    test_db_dialog_metadata_is_self_contained();
    test_db_dialog_update_existing_record_headless();
    test_db_dialog_insert_new_record_headless();
    TEST_END();
}
